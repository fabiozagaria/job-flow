-- Gerarchie JOINED: la tabella figlia condivide la PK con la tabella padre.

CREATE TABLE works (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE generate_pdf_works (
    id        BIGINT       PRIMARY KEY REFERENCES works (id),
    title     VARCHAR(255) NOT NULL,
    text_body VARCHAR(255) NOT NULL
);

CREATE TABLE results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE generated_pdf_results (
    id        BIGINT       PRIMARY KEY REFERENCES results (id),
    title     VARCHAR(255) NOT NULL,
    text_body VARCHAR(255) NOT NULL
);

CREATE TABLE jobs (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(255) NOT NULL,
    status    VARCHAR(255) NOT NULL
        CHECK (status IN ('CREATED', 'PROCESSING', 'COMPLETED', 'FAILED')),
    work_id   BIGINT UNIQUE REFERENCES works (id),
    result_id BIGINT UNIQUE REFERENCES results (id)
);
